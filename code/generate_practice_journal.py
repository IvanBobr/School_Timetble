def _fill_plan_table(doc: Document) -> None:
    plan = [
        ("1", DEPARTMENT, "Инструктаж по технике безопасности. Ознакомление с заданием.", f"{PRACTICE_START}-{PRACTICE_START}"),
        ("2", DEPARTMENT, "Анализ предметной области и формирование требований к системе.", "30.06.2026-01.07.2026"),
        ("3", DEPARTMENT, "Проектирование архитектуры и реализация серверного модуля (Flask).", "02.07.2026-04.07.2026"),
        ("4", DEPARTMENT, "Реализация модулей парсинга rasp.xls и changes.docx.", "05.07.2026-07.07.2026"),
        ("5", DEPARTMENT, "Разработка клиентского приложения (Tkinter), кэширование.", "08.07.2026-10.07.2026"),
        ("6", DEPARTMENT, "Тестирование, отладка, оформление отчёта по практике.", f"11.07.2026-{PRACTICE_END}"),
    ]

    for table in doc.tables:
        if not table.rows:
            continue
        headers = [_normalize_ws(c.text) for c in table.rows[0].cells]
        if len(headers) < 4 or "№" not in headers[0]:
            continue
        if "Место" not in headers[1] or "Тема" not in headers[2]:
            continue
        for i, row_data in enumerate(plan, start=1):
            if i >= len(table.rows):
                break
            row = table.rows[i]
            if len(row.cells) < 4:
                continue
            for j, val in enumerate(row_data):
                _replace_cell_text(row.cells[j], val)
        return


