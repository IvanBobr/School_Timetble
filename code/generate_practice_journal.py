def _insert_report_after_header(doc: Document) -> None:
    report_table_idx = None
    for i, table in enumerate(doc.tables):
        for row in table.rows:
            for cell in row.cells:
                if _normalize_ws(cell.text).lower().startswith("отчет обучающегося по практике"):
                    report_table_idx = i
                    for p in cell.paragraphs[1:]:
                        p._element.getparent().remove(p._element)
                    break

    body = doc.element.body
    if report_table_idx is None:
        return

    report_table = doc.tables[report_table_idx]
    tbl_el = report_table._tbl
    insert_after = tbl_el

    temp_doc = Document()
    for heading, level, paragraphs in _get_report_sections():
        if heading == "Список использованных источников":
            _add_heading(temp_doc, heading, level=level)
            for i, src in enumerate(_get_sources(), start=1):
                p = temp_doc.add_paragraph()
                p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
                p.paragraph_format.first_line_indent = Cm(1.25)
                run = p.add_run(f"{i}. {src}")
                _set_run_font(run)
            continue

        _add_heading(temp_doc, heading, level=level)
        for text in paragraphs:
            _add_body_paragraph(temp_doc, text)

    for child in list(temp_doc.element.body):
        if child.tag.endswith("sectPr"):
            continue
        insert_after.addnext(child)
        insert_after = child


def main() -> int:
    code_dir = Path(__file__).resolve().parent
    candidates = [p for p in code_dir.glob("*.docx") if p.name.lower() != "guide.docx"]
    if not candidates:
        raise SystemExit("Не найден шаблон журнала практики в папке code/")
    template_path = sorted(candidates, key=lambda p: p.stat().st_mtime, reverse=True)[0]

    doc = Document(str(template_path))

    _remove_editorial_paragraphs(doc)
    _fill_form_fields(doc)
    _fill_individual_task(doc)
    _fill_plan_table(doc)
    _insert_report_after_header(doc)
    _fill_signature_block(doc)
    _remove_red_runs(doc)

    out_path = code_dir.parent / "Журнал_практики.docx"
    try:
        doc.save(str(out_path))
        print(f"Saved: {out_path}")
    except PermissionError:
        alt = out_path.with_name(out_path.stem + "_NEW" + out_path.suffix)
        doc.save(str(alt))
        print(f"Saved (locked target, wrote new): {alt}")

    print(f"Template: {template_path.name}")
    return 0


