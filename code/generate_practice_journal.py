def _normalize_ws(s: str) -> str:
    return re.sub(r"\s+", " ", (s or "")).strip()


def _replace_cell_text(cell, new_text: str) -> None:
    for p in cell.paragraphs:
        for r in list(p.runs):
            r.text = ""
        p.text = ""
    p = cell.paragraphs[0] if cell.paragraphs else cell.add_paragraph()
    run = p.add_run(new_text)
    run.font.size = Pt(14)
    run.font.name = "Times New Roman"


def _set_run_font(run, *, bold: bool = False) -> None:
    run.font.name = "Times New Roman"
    run.font.size = Pt(14)
    run.bold = bold
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.rFonts
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    rfonts.set(qn("w:ascii"), "Times New Roman")
    rfonts.set(qn("w:hAnsi"), "Times New Roman")
    rfonts.set(qn("w:eastAsia"), "Times New Roman")


def _add_body_paragraph(doc: Document, text: str, *, indent: bool = True) -> None:
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    if indent:
        p.paragraph_format.first_line_indent = Cm(1.25)
    p.paragraph_format.line_spacing = 1.5
    run = p.add_run(text)
    _set_run_font(run)


def _add_heading(doc: Document, text: str, *, level: int = 1) -> None:
    p = doc.add_paragraph()
    if level == 1:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(text.upper())
        _set_run_font(run, bold=True)
    else:
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        p.paragraph_format.first_line_indent = Cm(1.25)
        run = p.add_run(text)
        _set_run_font(run, bold=True)
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(6)


def _add_list_item(doc: Document, text: str, marker: str) -> None:
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    p.paragraph_format.left_indent = Cm(1.25)
    p.paragraph_format.first_line_indent = Cm(0)
    run = p.add_run(f"{marker} {text}")
    _set_run_font(run)


def _remove_editorial_paragraphs(doc: Document) -> None:
    remove_keywords = (
        "дата утверждения и ознакомления",
        "примечание",
        "рекомендуемые позиции",
        "рекомендации:",
        "объем отчета",
        "объём отчета",
        "в отчете по практике после подписи",
        "в отчёте по практике после подписи",
        "примечания и рекомендации",
        "красный текст",
        "далее следует отчет",
        "далее следует отчёт",
        "необходимо завершать фразой",
        "оценка пишется прописью",
        "[тз:",
        "тз:",
    )
    for para in list(doc.paragraphs):
        t = _normalize_ws(para.text).lower()
        if any(k in t for k in remove_keywords):
            el = para._element
            el.getparent().remove(el)


def _remove_red_runs(doc: Document) -> None:
    """Удаляет красные фрагменты из шаблона (примечания к оформлению)."""
    red_rgb = {"FF0000", "ff0000"}

    def clean_paragraph(paragraph) -> None:
        for run in list(paragraph.runs):
            rgb = None
            if run.font.color and run.font.color.rgb:
                rgb = str(run.font.color.rgb)
            if rgb in red_rgb:
                run.text = ""

    for para in doc.paragraphs:
        clean_paragraph(para)

    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for para in cell.paragraphs:
                    clean_paragraph(para)
                # убрать пустые абзацы в ячейках
                full = _normalize_ws(cell.text)
                if not full:
                    _replace_cell_text(cell, "")


def _clean_cell_red_and_tz(cell) -> None:
    text = cell.text
    if "[ТЗ:" in text or "ТЗ:" in text:
        cleaned = re.sub(r"\[ТЗ:[^\]]*\]", "", text).strip()
        if cleaned:
            _replace_cell_text(cell, cleaned)
        else:
            _replace_cell_text(cell, "")


def _fill_form_fields(doc: Document) -> None:
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                t = _normalize_ws(cell.text)
                if not t:
                    continue

                if "Иванов Иван Иванович" in t:
                    _replace_cell_text(cell, STUDENT_FIO)
                    continue

                if "М8О-" in t and "ХХХ" in t:
                    _replace_cell_text(cell, STUDENT_GROUP)
                    continue

                if re.search(r"\bОЦ\s*8\b", t) and ("___" in t or "__" in t):
                    if "кафедра" in t.lower():
                        _replace_cell_text(cell, DEPARTMENT)
                    elif "наименование организации" in t.lower() or t.startswith("Наименование"):
                        _replace_cell_text(cell, PLACE_OFFICIAL)
                    else:
                        _replace_cell_text(cell, DEPARTMENT)
                    continue

                if "Крылов" in t:
                    if "оценка" in t.lower():
                        _replace_cell_text(cell, f"_________________ {SUPERVISOR_ORDER}")
                    else:
                        table_flat = " ".join(
                            _normalize_ws(c.text).lower() for r in table.rows for c in r.cells
                        )
                        if "отзыв" in table_flat:
                            _replace_cell_text(cell, f"/{SUPERVISOR_FACT}/")
                        elif "организации" in table_flat or "предприятия" in table_flat:
                            if "утверждаю" in table_flat and "организации" in t.lower():
                                _replace_cell_text(cell, f"/{SUPERVISOR_FACT}/")
                            elif "инструктаж" in table_flat:
                                _replace_cell_text(cell, f"/{SUPERVISOR_ORDER.split()[-3]} {SUPERVISOR_ORDER.split()[-2]} {SUPERVISOR_ORDER.split()[-1]}/")
                            else:
                                short = " ".join(SUPERVISOR_ORDER.split()[-3:])
                                _replace_cell_text(cell, f"/{short}/")
                        else:
                            short = " ".join(SUPERVISOR_ORDER.split()[-3:])
                            _replace_cell_text(cell, f"/{short}/")
                    continue

                if re.search(r"\b29\.06\.2026\b", t) and "дата начала" in " ".join(
                    _normalize_ws(c.text).lower() for r in table.rows for c in r.cells
                ):
                    _replace_cell_text(cell, PRACTICE_START)
                    continue

                if re.search(r"\b12\.07\.2026\b", t) and "дата окончания" in " ".join(
                    _normalize_ws(c.text).lower() for r in table.rows for c in r.cells
                ):
                    _replace_cell_text(cell, PRACTICE_END)
                    continue

                if "01.03.02" in t or "02.03.02" in t:
                    _replace_cell_text(cell, DIRECTION)
                    continue

                if "ознакомительная" in t and "технологическая" in t:
                    _replace_cell_text(cell, PRACTICE_TYPE)
                    continue

                if t == "/____________________/":
                    _replace_cell_text(cell, f"/{STUDENT_FIO}/")
                    continue

                _clean_cell_red_and_tz(cell)


